import Link from 'next/link';
import { Icon } from '@/components/Icon';
import { Empty, PageHead, Download } from '@/components/ui';
import { requireAdmin } from '@/lib/auth/current-user';
import { employeeMap } from '@/lib/data/employees';
import { buildRun, periodsForYear } from '@/lib/data/payroll';
import { REPORTS, type ReportName } from '@/lib/data/reports';
import { currentSchoolYear } from '@/lib/data/years';
import { fmtDate, money, shortName, todayIso } from '@/lib/format';
import { reportRuns } from '@/lib/store';

export default async function ReportsPage() {
  await requireAdmin();
  const year = await currentSchoolYear();
  const runs = (await reportRuns.all()).reverse();
  const byId = await employeeMap();
  const last = (name: string) => runs.find((r) => r.report === name)?.at;
  const periods = year
    ? (await periodsForYear(year.id)).filter((p) => p.startsOn <= todayIso()).slice(-6)
    : [];
  const trend = await Promise.all(
    periods.map(async (p) => ({
      p,
      total: (await buildRun(p)).filter((l) => l.status === 'READY').reduce((s, l) => s + l.totalCents, 0),
    })),
  );
  const max = Math.max(1, ...trend.map((t) => t.total));
  const k = (c: number) =>
    c >= 100_000_00 ? `$${Math.round(c / 100_000)}k` : `$${(c / 100_000).toFixed(1)}k`;
  return (
    <>
      <PageHead title="Reports" sub="Export and review data across every part of the portal" />
      <div className="panel mb">
        <div className="panel-head">
          <h3>Payroll trend — last {trend.length} pay periods</h3>
        </div>
        <div className="panel-body">
          {trend.length === 0 ? (
            <p className="muted">No pay periods yet.</p>
          ) : (
            <div className="chart-row" role="list" aria-label="Payroll totals by pay period">
              {trend.map(({ p, total }) => (
                <div
                  className="chart-bar"
                  key={p.id}
                  role="listitem"
                  aria-label={`${fmtDate(p.startsOn)}${p.status === 'DRAFT' ? ' (draft)' : ''}: ${money(total)} before tax`}
                >
                  <div className="val" aria-hidden="true">
                    {k(total)}
                  </div>
                  <div
                    aria-hidden="true"
                    className={`fill${p.status === 'DRAFT' ? ' flag' : ''}`}
                    style={{ height: `${Math.max(2, (total / max) * 100)}%` }}
                  />
                  <div className="lbl" aria-hidden="true">
                    {fmtDate(p.startsOn, { year: false })}
                    {p.status === 'DRAFT' ? ' (draft)' : ''}
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>
      <div className="report-grid">
        {(Object.keys(REPORTS) as ReportName[]).map((name) => (
          <div className="report-card" key={name}>
            <div className="rc-icon">
              <Icon name="chart" />
            </div>
            <h4>{REPORTS[name].title}</h4>
            <p>{REPORTS[name].description}</p>
            <div className="rc-meta">
              {last(name) ? `Last generated ${fmtDate(last(name))}` : 'Not generated yet'}
            </div>
            <div className="rc-actions">
              <Download className="btn btn-secondary btn-sm" href={`/api/reports/${name}.csv`}>
                Export CSV
              </Download>
              <Link className="btn btn-secondary btn-sm" href={`/reports/${name}`}>
                Export PDF
              </Link>
            </div>
          </div>
        ))}
      </div>
      <div className="panel">
        <div className="panel-head">
          <h3>Recently generated</h3>
        </div>
        {runs.length === 0 ? (
          <Empty title="No reports generated yet" />
        ) : (
          <table>
            <thead>
              <tr>
                <th>Report</th>
                <th>Generated by</th>
                <th>Date</th>
                <th>Format</th>
                <th />
              </tr>
            </thead>
            <tbody>
              {runs.slice(0, 10).map((r) => (
                <tr key={r.id}>
                  <td>{REPORTS[r.report as ReportName]?.title ?? r.report}</td>
                  <td>{shortName(byId.get(r.generatedById)?.name ?? '?')}</td>
                  <td>{fmtDate(r.at)}</td>
                  <td>{r.format}</td>
                  <td className="num">
                    <a
                      className="link"
                      href={r.format === 'CSV' ? `/api/reports/${r.report}.csv` : `/reports/${r.report}`}
                    >
                      Generate again
                    </a>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </div>
    </>
  );
}
